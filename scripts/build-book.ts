import { readFile, readdir, writeFile } from "node:fs/promises";
import { extname, relative, resolve, sep } from "node:path";

const root = resolve(import.meta.dirname, "..");
const chapterDirectory = resolve(root, "book", "chapters");
const output = resolve(
  root,
  "book",
  "building-zero-knowledge-blind-credentials.md",
);
const includePattern = /^\{\{blindpass-include:([^}]+)\}\}$/gm;

function language(path: string): string {
  const languages: Record<string, string> = {
    ".ts": "typescript",
    ".tsx": "tsx",
    ".js": "javascript",
    ".mjs": "javascript",
    ".json": "json",
    ".sql": "sql",
    ".yaml": "yaml",
    ".yml": "yaml",
  };
  return languages[extname(path)] ?? "text";
}

async function expand(source: string): Promise<string> {
  const matches = [...source.matchAll(includePattern)];
  let rendered = source;
  for (const match of matches) {
    const requested = match[1].trim();
    const absolute = resolve(root, requested);
    if (absolute !== root && !absolute.startsWith(`${root}${sep}`))
      throw new Error(`Book include escapes the repository: ${requested}`);
    const code = (await readFile(absolute, "utf8")).trimEnd();
    const listing = `**Listing — \`${requested}\` (complete file)**\n\n\`\`\`${language(requested)}\n${code}\n\`\`\``;
    rendered = rendered.replace(match[0], listing);
  }
  return rendered;
}

const chapterNames = (await readdir(chapterDirectory))
  .filter((name) => /^(?:0[1-9]|1[0-3])-.*\.md$/.test(name))
  .sort();
if (chapterNames.length !== 13)
  throw new Error(`Expected 13 chapters; found ${chapterNames.length}`);

const chapters = await Promise.all(
  chapterNames.map(async (name) =>
    expand(await readFile(resolve(chapterDirectory, name), "utf8")),
  ),
);
const frontMatter = await readFile(
  resolve(chapterDirectory, "00-front-matter.md"),
  "utf8",
);
const manuscript = [
  "<!-- Generated by pnpm book:build. Edit book/chapters and source files. -->",
  frontMatter.trim(),
  ...chapters.map((chapter) => chapter.trim()),
  "",
].join("\n\n");

if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing !== manuscript) {
    console.error(`${relative(root, output)} is stale; run pnpm book:build`);
    process.exitCode = 1;
  }
} else {
  await writeFile(output, manuscript);
  console.log(
    `Wrote ${relative(root, output)} from ${chapterNames.length} chapters.`,
  );
}
